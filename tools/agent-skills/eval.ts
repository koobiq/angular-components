import { spawnSync } from 'child_process';
import { chmodSync, copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { join, relative } from 'path';
import { PACKAGE_DIST_DIR, REPO_ROOT, SKILL_DIST_DIR, SKILL_NAME } from './constants';

const EVALS_SOURCE_DIR = join(REPO_ROOT, 'packages/agent-skills/evals');

/** A throwaway plugin around the built skill: `claude plugin eval` evaluates plugins, not bare skill folders. */
const EVAL_PLUGIN_DIR = join(REPO_ROOT, 'dist/agent-skills-eval');

/**
 * Seeds each run's empty workspace with an Angular project that has the built @koobiq/components installed, so the
 * agent finds `node_modules/@koobiq/components/agent-docs` and the typings the way a consumer's agent does.
 */
const fixtureScript = (version: string): string => `#!/usr/bin/env bash
# Generated by tools/agent-skills/eval.ts.
set -euo pipefail

mkdir -p node_modules/@koobiq/components src/app
cp -R '${PACKAGE_DIST_DIR}/.' node_modules/@koobiq/components/

cat > package.json <<'JSON'
{
    "name": "koobiq-eval-app",
    "private": true,
    "dependencies": {
        "@angular/core": "^20.0.0",
        "@angular/forms": "^20.0.0",
        "@koobiq/components": "${version}"
    }
}
JSON

cat > src/app/app.ts <<'TS'
import { Component } from '@angular/core';

@Component({
    selector: 'app-root',
    template: ''
})
export class App {}
TS
`;

const copyDirectory = (source: string, target: string): void => {
    mkdirSync(target, { recursive: true });

    for (const entry of readdirSync(source, { withFileTypes: true })) {
        const [from, to] = [join(source, entry.name), join(target, entry.name)];

        if (entry.isDirectory()) {
            copyDirectory(from, to);
        } else {
            copyFileSync(from, to);
        }
    }
};

const assemblePlugin = (): string => {
    if (!existsSync(join(SKILL_DIST_DIR, 'SKILL.md'))) {
        throw new Error('The skill is not built: run "yarn run build:components && yarn run build:agent-skills" first');
    }

    const { version } = JSON.parse(readFileSync(join(PACKAGE_DIST_DIR, 'package.json'), 'utf-8'));

    rmSync(EVAL_PLUGIN_DIR, { recursive: true, force: true });
    mkdirSync(join(EVAL_PLUGIN_DIR, '.claude-plugin'), { recursive: true });
    writeFileSync(
        join(EVAL_PLUGIN_DIR, '.claude-plugin/plugin.json'),
        `${JSON.stringify({ name: 'koobiq', version, description: 'Koobiq agent skill, assembled for evals' }, null, 4)}\n`
    );
    copyDirectory(SKILL_DIST_DIR, join(EVAL_PLUGIN_DIR, 'skills', SKILL_NAME));
    copyDirectory(EVALS_SOURCE_DIR, join(EVAL_PLUGIN_DIR, 'evals'));

    for (const entry of readdirSync(join(EVAL_PLUGIN_DIR, 'evals'), { withFileTypes: true })) {
        const caseDir = join(EVAL_PLUGIN_DIR, 'evals', entry.name);

        if (entry.isDirectory() && existsSync(join(caseDir, 'case.yaml'))) {
            writeFileSync(join(caseDir, 'fixture.sh'), fixtureScript(version));
            chmodSync(join(caseDir, 'fixture.sh'), 0o755);
        }
    }

    return version;
};

/**
 * `yarn run eval:agent-skills [claude plugin eval options]`: runs the suite in packages/agent-skills/evals against
 * the built skill, each case with the skill and without it. Every run is a real model call on your account; narrow
 * a run with `--case`, `--tag` or `--runs`, and cap it with `--max-cost-usd`.
 */
if (require.main === module) {
    try {
        const version = assemblePlugin();
        const args = [
            'plugin',
            'eval',
            EVAL_PLUGIN_DIR,
            ...process.argv.slice(2),
            // Last: `--allow-tools` takes the arguments after it as its list.
            '--scaffold',
            '--allow-tools',
            'Write',
            'Edit'
        ];

        console.info(`Evaluating the ${SKILL_NAME} skill of @koobiq/components ${version}: claude ${args.join(' ')}`);
        console.info(`Results: ${relative(REPO_ROOT, join(EVAL_PLUGIN_DIR, 'evals/results'))}`);

        const { status } = spawnSync('claude', args, { stdio: 'inherit' });

        process.exitCode = status ?? 1;
    } catch (error) {
        console.error(`❌ ${error instanceof Error ? error.message : error}`);
        process.exitCode = 1;
    }
}
